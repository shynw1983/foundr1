export function replenishmentText(language: Language, text: string, values?: Record<string, string | number>) {
  const entry = copy[text as keyof typeof copy];
  const translated = language === "ja" || !entry ? text : entry[language === "zh-Hant" ? 1 : 0];
  return values ? translated.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token)) : translated;
}
