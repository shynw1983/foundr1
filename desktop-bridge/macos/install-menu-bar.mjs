import {execFile} from 'node:child_process';
import {mkdir,writeFile} from 'node:fs/promises';
import {homedir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {promisify} from 'node:util';
const exec=promisify(execFile);
const root=path.dirname(fileURLToPath(import.meta.url));
const app=path.join(homedir(),'Applications','Foundr1 Bridge.app');
const binary=path.join(app,'Contents','MacOS','Foundr1Bridge');
const label='jp.foundr1.bridge-menu';
const domain=`gui/${process.getuid()}`;
const plist=path.join(homedir(),'Library','LaunchAgents',`${label}.plist`);
const xml=value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
await mkdir(path.dirname(binary),{recursive:true});
await mkdir(path.dirname(plist),{recursive:true});
await exec('xcrun',['swiftc',path.join(root,'BridgeStatus.swift'),'-target',`${process.arch==='arm64'?'arm64':'x86_64'}-apple-macosx13.0`,'-o',`${binary}.new`,'-framework','AppKit','-framework','UserNotifications'],{timeout:60000});
await exec('launchctl',['bootout',`${domain}/${label}`]).catch(()=>{});
const {rename}=await import('node:fs/promises');await rename(`${binary}.new`,binary);
await writeFile(path.join(app,'Contents','Info.plist'),`<?xml version="1.0"?><plist version="1.0"><dict><key>CFBundleExecutable</key><string>Foundr1Bridge</string><key>CFBundleIdentifier</key><string>jp.foundr1.bridge-menu</string><key>CFBundleName</key><string>Foundr1 Bridge</string><key>CFBundlePackageType</key><string>APPL</string><key>LSMinimumSystemVersion</key><string>13.0</string><key>CFBundleVersion</key><string>1</string><key>LSUIElement</key><true/></dict></plist>`);
await exec('codesign',['--force','--sign','-',app],{timeout:15000});
await writeFile(plist,`<?xml version="1.0"?><plist version="1.0"><dict><key>Label</key><string>${label}</string><key>ProgramArguments</key><array><string>${xml(binary)}</string></array><key>RunAtLoad</key><true/><key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict><key>ThrottleInterval</key><integer>10</integer></dict></plist>`);
await exec('launchctl',['bootstrap',domain,plist]);
await exec('launchctl',['kickstart',`${domain}/${label}`]);
console.log(JSON.stringify({app,label,installed:true}));
