export function withPlatformTargetAliases(platform, target) {
  const map = platform === "rocket_now"
    ? ROCKET_ALIASES
    : platform === "demae_can"
      ? DEMAE_ALIASES
      : null;
  const extra = map?.get(String(target?.label ?? "").trim()) ?? [];
  return {
    ...target,
    aliases: Array.from(new Set([...(Array.isArray(target?.aliases) ? target.aliases : []), ...extra]))
  };
}
